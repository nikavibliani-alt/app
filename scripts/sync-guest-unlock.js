#!/usr/bin/env node
/** Copy computeGuestUnlock logic from shared/guest-unlock.js → pipeline-functions/lib/guest-unlock.js */
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SHARED = join(ROOT, 'shared/guest-unlock.js');
const SERVER = join(ROOT, 'pipeline-functions/lib/guest-unlock.js');

const shared = readFileSync(SHARED, 'utf8');
const server = readFileSync(SERVER, 'utf8');

function extractBlock(src, fnName, nextFnName) {
  const start = src.indexOf(`function ${fnName}`);
  const end = src.indexOf(`function ${nextFnName}`, start);
  if (start < 0 || end < 0) throw new Error(`Could not extract ${fnName}`);
  return src.slice(start, end);
}

const computeBlock = extractBlock(shared, 'computeGuestUnlock', 'isGuestUnlocked');
const isStart = shared.indexOf('function isGuestUnlocked');
const isEnd = shared.indexOf('if (typeof module', isStart);
if (isStart < 0 || isEnd < 0) throw new Error('Could not extract isGuestUnlocked');
const isGuestBlock = shared.slice(isStart, isEnd);

const parseCheckInHour = `
function parseCheckInHour(checkInTime) {
  if (!checkInTime) return DEFAULT_CHECK_IN_HOUR;
  const h = parseInt(String(checkInTime).split(':')[0], 10);
  return Number.isFinite(h) ? h : DEFAULT_CHECK_IN_HOUR;
}
`;

const out = `'use strict';
/**
 * Server copy of shared/guest-unlock.js — keep logic in sync.
 * Generated by scripts/sync-guest-unlock.js — do not edit computeGuestUnlock by hand.
 * See pipeline-functions/tests/guestUnlock.test.js
 */

const TBILISI_TZ = 'Asia/Tbilisi';
const DEFAULT_CHECK_IN_HOUR = 15;
const HK_EARLY_HOUR = 11;

function tbilisiNow() {
  return new Date(Date.now() + 4 * 3600 * 1000);
}

function tbilisiToday() {
  return tbilisiNow().toISOString().slice(0, 10);
}

function tbilisiHour() {
  return tbilisiNow().getUTCHours();
}

function normalizeStayDate(v) {
  if (v == null || v === '') return '';
  if (typeof v === 'string') {
    const m = v.match(/^(\\d{4}-\\d{2}-\\d{2})/);
    return m ? m[1] : '';
  }
  if (typeof v.toDate === 'function') {
    return v.toDate().toISOString().slice(0, 10);
  }
  if (v.seconds != null) {
    return new Date(v.seconds * 1000).toISOString().slice(0, 10);
  }
  return '';
}

${computeBlock}
${isGuestBlock}${parseCheckInHour}
module.exports = {
  TBILISI_TZ,
  DEFAULT_CHECK_IN_HOUR,
  HK_EARLY_HOUR,
  tbilisiNow,
  tbilisiToday,
  tbilisiHour,
  normalizeStayDate,
  computeGuestUnlock,
  isGuestUnlocked,
  parseCheckInHour,
};
`;

writeFileSync(SERVER, out);
console.log('Synced pipeline-functions/lib/guest-unlock.js from shared/guest-unlock.js');
