// Admin: the Entrance / building code fields (per unit, per type) save where the guest page reads them.
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const assert = require('assert');
const h = require('./e2e.cjs');
let passed = 0; const ok = n => { passed++; console.log('PASS ' + n); };
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, args: ['--no-sandbox'] });
  const env = await h.open(browser, { apiOn: true, startIso: '2026-10-12T06:00:00Z' });
  await env.page.addInitScript(() => { localStorage.setItem('maxela_admin_authed', 'yes_' + Date.now()); });
  await env.page.goto('http://test.local/checkin-admin.html');
  await env.page.waitForFunction(() => typeof window.openAptEditor === 'function' && typeof window.openAptType === 'function', null, { timeout: 20000 });
  await env.page.waitForTimeout(1500);
  await env.page.evaluate(() => window.openAptEditor('6-1'));
  await env.page.waitForSelector('#apt-entranceCode', { timeout: 5000 });
  await env.page.fill('#apt-entranceCode', '9911#');
  await env.page.evaluate(() => window.saveAptData ? window.saveAptData() : window.saveApt());
  await env.page.waitForTimeout(500);
  let docs = await env.page.evaluate(() => JSON.parse(JSON.stringify(window.__DB.docs)));
  assert.equal(docs['checkin_apartments/6-1'].entranceCode, '9911#');
  ok('unit page: entrance code field saves on the apartment');
  if (process.env.SHOT_UNIT) await env.page.screenshot({ path: process.env.SHOT_UNIT });
  await env.page.evaluate(() => { window.closeAptEditor && window.closeAptEditor(); });
  await env.page.evaluate(() => { window.openAptType('MAXELA'); window.atSetTab('steps'); });
  await env.page.waitForSelector('#at-entrance-code', { timeout: 5000 });
  await env.page.fill('#at-entrance-code', '6622#');
  await env.page.evaluate(() => window.atSaveEntranceCode());
  await env.page.waitForTimeout(500);
  docs = await env.page.evaluate(() => JSON.parse(JSON.stringify(window.__DB.docs)));
  assert.equal(docs['checkin_type_codes/MAXELA'].entranceCode, '6622#');
  assert.ok(!JSON.stringify(docs['checkin_admin/config'] || {}).includes('6622'), 'the code is never saved inside the type config');
  ok('type page: entrance code saves in checkin_type_codes, never in the config');
  if (process.env.SHOT_TYPE) await env.page.screenshot({ path: process.env.SHOT_TYPE });
  await env.page.fill('input[oninput*="atSetBuildingLabel"]', 'Main door code');
  await env.page.evaluate(() => window.atSave());
  await env.page.waitForTimeout(500);
  docs = await env.page.evaluate(() => JSON.parse(JSON.stringify(window.__DB.docs)));
  assert.equal(docs['checkin_admin/config'].aptTypes.MAXELA.access.buildingLabel, 'Main door code');
  ok('type page: the card title is saved with the type');
  // check-out steps of the type: own tab, same editor, saved with the type; arrival steps are untouched
  await env.page.evaluate(() => { window.atSetTab('checkout'); window.atAddStep(); });
  await env.page.waitForSelector('#at-step-text', { timeout: 5000 });
  await env.page.evaluate(() => { window.atSetStep('title', 'Close the windows'); window.atSetStep('text', 'Leave {room} tidy. Entrance code: {entrance code}'); });
  await env.page.evaluate(() => window.closeAptType());   // back to the list
  await env.page.waitForSelector('.at-step', { timeout: 5000 });
  if (process.env.SHOT_CO) await env.page.screenshot({ path: process.env.SHOT_CO });
  await env.page.evaluate(() => window.atSave());
  await env.page.waitForTimeout(500);
  docs = await env.page.evaluate(() => JSON.parse(JSON.stringify(window.__DB.docs)));
  const cfg = docs['checkin_admin/config'].aptTypes.MAXELA;
  assert.equal(cfg.checkoutSteps.length, 1);
  assert.equal(cfg.checkoutSteps[0].title, 'Close the windows');
  assert.match(cfg.checkoutSteps[0].text, /\{entrance code\}/);
  assert.equal((cfg.steps || []).length, 0, 'arrival steps are not touched');
  ok('type page: Check-out steps tab adds a step that is saved with the type (arrival steps untouched)');
  const tabs = await env.page.evaluate(() => { const t = document.getElementById('apt-type-tabs'); return { n: t.children.length, wide: t.scrollWidth > t.clientWidth + 2 }; });
  assert.equal(tabs.n, 4);
  assert.equal(tabs.wide, false, 'the four tabs fit at phone width');
  ok('type page: the four tabs fit at 390px');
  // a unit's own check-out steps
  await env.page.evaluate(() => { window.closeAptType(true); window.openAptEditor('6-1'); });
  await env.page.waitForSelector('#aptCheckoutSteps', { timeout: 5000 });
  assert.match(await env.page.evaluate(() => document.getElementById('aptCheckoutSteps').parentElement.innerText), /Close the windows/);
  await env.page.evaluate(() => window.coAddText());
  await env.page.waitForSelector('#co-cap-0', { timeout: 5000 });
  await env.page.fill('#co-cap-0', 'Take the trash out');
  await env.page.evaluate(() => window.saveAptData());
  await env.page.waitForTimeout(500);
  docs = await env.page.evaluate(() => JSON.parse(JSON.stringify(window.__DB.docs)));
  assert.deepEqual(docs['checkin_apartments/6-1'].checkoutPhotoCaptions, ['Take the trash out']);
  assert.deepEqual(docs['checkin_apartments/6-1'].checkoutPhotos, ['']);
  if (process.env.SHOT_COUNIT) { await env.page.evaluate(() => document.getElementById('aptCheckoutSteps').scrollIntoView()); await env.page.screenshot({ path: process.env.SHOT_COUNIT }); }
  await env.page.evaluate(() => window.coAddText());
  await env.page.waitForSelector('#co-cap-1', { timeout: 5000 });
  assert.equal(await env.page.inputValue('#co-cap-0'), 'Take the trash out', 'typed words survive adding a step');
  await env.page.evaluate(() => window.coMove(1, -1));
  await env.page.waitForTimeout(300);
  await env.page.evaluate(() => { window.confirm = () => true; return window.coDelete(0); });
  await env.page.waitForTimeout(500);
  docs = await env.page.evaluate(() => JSON.parse(JSON.stringify(window.__DB.docs)));
  assert.deepEqual(docs['checkin_apartments/6-1'].checkoutPhotoCaptions, ['Take the trash out']);
  ok('unit page: own check-out steps add, keep typed words, move, delete and save');
  assert.deepEqual(env.logs.filter(l => l.startsWith('PAGEERROR')), []);
  console.log('\nALL ' + passed + ' ADMIN ENTRANCE CODE CHECKS PASSED');
  await browser.close();
})().catch(e => { console.error('FAIL', e); process.exit(1); });
